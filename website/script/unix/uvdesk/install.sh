#!/bin/sh -eux

echo "[WADDLE NOTICE] Starting website installation."

# Create source directory.
if [ ! -d "./website/src" ]; then
    mkdir -p "./website/src"
fi

# Download UVdesk via Composer.
echo "[WADDLE] Downloading UVdesk version {{tags.website.version.full_raw}}."
docker compose exec -T php composer create-project \
    uvdesk/community-skeleton:{{tags.website.version.full_raw}} "{{project_path 'website/src'}}" \
    --no-interaction --no-scripts

# Pin twig/twig to ensure we get a working instance.
echo "[WADDLE] Pinning twig/twig below the symfony/twig-bundle-incompatible 3.29.0."
docker compose exec -T php composer require twig/twig:"^3.0,<3.29" --no-interaction --no-scripts \
    --working-dir="{{project_path 'website/src'}}"

# Apply configuration.
echo "[WADDLE] Applying configuration."

# Capture APP_SECRET generated by Symfony Flex during composer create-project before overwriting .env.
APP_SECRET=$(grep "^APP_SECRET=" "./website/src/.env" 2>/dev/null | cut -d= -f2- | tr -dc '[:alnum:]' || true)
cp "./website/conf/uvdesk/.env" "./website/src/.env"

# Write the captured APP_SECRET back in. Avoid `sed -i` (not portable — BSD/macOS sed
# requires a backup-suffix argument); write through a temp file in the same directory.
if [ -n "${APP_SECRET}" ]; then
    sed "s/^APP_SECRET=$/APP_SECRET=${APP_SECRET}/" "./website/src/.env" > "./website/src/.env.tmp"
    mv "./website/src/.env.tmp" "./website/src/.env"
fi

# Patch Doctrine's Setup.php: it hardcodes 127.0.0.1 for Redis when the extension is loaded,
# which causes "Connection refused" in Docker where Redis is at hostname 'redis'.
# See: https://github.com/uvdesk/community-skeleton/issues/364
# Guarded: doctrine/orm 3.x removed Tools/Setup.php, so only patch it when present. Avoid
# `sed -i` for portability (BSD/macOS sed requires a backup-suffix argument).
DOCTRINE_SETUP="./website/src/vendor/doctrine/orm/src/Tools/Setup.php"
if [ -f "${DOCTRINE_SETUP}" ]; then
    echo "[WADDLE] Patching Doctrine Setup.php for Docker Redis hostname."
    sed "s/\$redis->connect('127\.0\.0\.1')/\$redis->connect('redis')/" "${DOCTRINE_SETUP}" \
        > "${DOCTRINE_SETUP}.tmp"
    mv "${DOCTRINE_SETUP}.tmp" "${DOCTRINE_SETUP}"
fi

# Run the UVdesk helpdesk configuration wizard.
# Uses APP_ENV=dev so DoctrineFixturesBundle (dev-only) is available for seeding roles.
# Piped inputs:
#   Y                 → Update database schema? [Y/N]
#   Y                 → Create super admin? [Y/N]
#   admin_email       → Email
#   admin_name        → Name (first + last)
#   admin_password    → Password
#   admin_password    → Confirm Password
echo "[WADDLE] Configuring UVdesk."
printf 'Y\nY\n%s\n%s %s\n%s\n%s\n' \
    "{{public.website.admin_email}}" \
    "{{public.website.admin_firstname}}" \
    "{{public.website.admin_lastname}}" \
    "${WADDLE_ADMIN_PASSWORD}" \
    "${WADDLE_ADMIN_PASSWORD}" \
    | docker compose exec -T -e APP_ENV=dev php php "{{project_path 'website/src'}}/bin/console" uvdesk:configure-helpdesk

# Install bundle public assets. Normally handled by composer.json's own auto-scripts
# (assets:install %PUBLIC_DIR%), skipped above via --no-scripts alongside cache:clear.
echo "[WADDLE] Installing public assets."
docker compose exec -T php php "{{project_path 'website/src'}}/bin/console" assets:install \
    "{{project_path 'website/src'}}/public"

# Mail and site URL (mailbox + support sender). Copied after uvdesk:configure-helpdesk so the wizard
# can't overwrite them; see the rendered files for details.
echo "[WADDLE] Applying mail configuration."
cp "./website/conf/uvdesk/uvdesk_mailbox.yaml" "./website/src/config/packages/uvdesk_mailbox.yaml"
cp "./website/conf/uvdesk/waddle.yaml" "./website/src/config/packages/waddle.yaml"

# Clear caches.
echo "[WADDLE] Clearing caches."
docker compose exec -T php php "{{project_path 'website/src'}}/bin/console" cache:clear

# Ensure that daemon-owned directories are owned by the unprivileged worker user (when docker
# is running in rootless mode).
echo "[WADDLE] Fixing permissions."
docker compose exec -T php sh -c 'if [ "$(id -u)" = 0 ] && [ $# -gt 0 ]; then chown -R {{get_daemon_user public.php.docker}}:{{get_daemon_group public.php.docker}} "$@"; fi' sh \
    {{#each (get_daemon_owned_dirs public.website.platform)}}"{{project_path 'website/src'}}/{{this}}" {{/each}}
