$ErrorActionPreference = "Stop"

Write-Host "[WADDLE NOTICE] Starting website installation."

# Download UVdesk via Composer. --no-scripts: composer.json wires cache:clear/assets:install as
# post-install-cmd, and twig/twig resolves (loose "^2.12|^3.0" constraint) to whatever is newest —
# letting that run here would hit the twig/twig incompatibility below before we've had a chance to
# pin it, aborting create-project outright.
Write-Host "[WADDLE] Downloading UVdesk version {{tags.website.version.full_raw}}."
docker compose exec -T php composer create-project uvdesk/community-skeleton:{{tags.website.version.full_raw}} `
    "{{project_path 'website/src'}}" --no-interaction --no-scripts
if ($LASTEXITCODE -ne 0) { throw "Failed to download UVdesk." }

# Pin twig/twig below the version that broke this stack. Twig 3.29.0 changed
# TemplateWrapper::unwrap() to require an Environment argument; symfony/twig-bundle ^5.4 (what
# UVdesk's community-skeleton requires) still calls the old zero-argument form from
# CacheWarmer/TemplateCacheWarmer.php, so any cache:clear fatals with an ArgumentCountError on
# whatever latest 3.x composer's loose constraint resolves to. Confirmed against the
# 3.10.0-3.29.0 tag range that 3.29.0 is where the signature changed; 3.28.0 and earlier are
# unaffected. --no-scripts here too: the pin itself doesn't need a cache warm, and .env is still
# Flex's default at this point, not Waddle's.
Write-Host "[WADDLE] Pinning twig/twig below the symfony/twig-bundle-incompatible 3.29.0."
docker compose exec -T php composer require twig/twig:"^3.0,<3.29" --no-interaction --no-scripts `
    --working-dir="{{project_path 'website/src'}}"
if ($LASTEXITCODE -ne 0) { throw "Failed to pin twig/twig." }

# Apply configuration.
Write-Host "[WADDLE] Applying configuration."

# Capture APP_SECRET generated by Symfony Flex during composer create-project before overwriting .env.
$appSecret = (docker compose exec -T php sh -c "grep '^APP_SECRET=' '{{project_path 'website/src'}}/.env' 2>/dev/null") -replace "^APP_SECRET=", ""
docker compose exec -T php cp "{{project_path 'website/conf/uvdesk/.env'}}" "{{project_path 'website/src'}}/.env"
if ($LASTEXITCODE -ne 0) { throw "Failed to apply configuration." }

# Write the captured APP_SECRET back in.
if ($appSecret) {
    docker compose exec -T php sed -i "s/^APP_SECRET=$/APP_SECRET=$appSecret/" "{{project_path 'website/src'}}/.env"
    if ($LASTEXITCODE -ne 0) { throw "Failed to restore APP_SECRET." }
}

# Patch Doctrine's Setup.php: it hardcodes 127.0.0.1 for Redis when the extension is loaded,
# which causes "Connection refused" in Docker where Redis is at hostname 'redis'.
# See: https://github.com/uvdesk/community-skeleton/issues/364
# Guarded: doctrine/orm 3.x removed Tools/Setup.php, so only patch it when present.
$doctrineSetup = "{{project_path 'website/src'}}/vendor/doctrine/orm/src/Tools/Setup.php"
docker compose exec -T php sh -c "test -f '$doctrineSetup'"
if ($LASTEXITCODE -eq 0) {
    Write-Host "[WADDLE] Patching Doctrine Setup.php for Docker Redis hostname."
    docker compose exec -T php sed -i "s/`$redis->connect('127.0.0.1')/`$redis->connect('redis')/" "$doctrineSetup"
    if ($LASTEXITCODE -ne 0) { throw "Failed to patch Doctrine Setup.php." }
}

# Run the UVdesk helpdesk configuration wizard.
# Uses APP_ENV=dev so DoctrineFixturesBundle (dev-only) is available for seeding roles.
# Piped inputs: Y (update schema), Y (create super admin), email, name, password, confirm password.
Write-Host "[WADDLE] Configuring UVdesk."
"Y`nY`n{{public.website.admin_email}}`n{{public.website.admin_firstname}} {{public.website.admin_lastname}}`n$env:WADDLE_ADMIN_PASSWORD`n$env:WADDLE_ADMIN_PASSWORD`n" | docker compose exec -i `
    -u root `
    -e APP_ENV=dev `
    php php "{{project_path 'website/src'}}/bin/console" uvdesk:configure-helpdesk
if ($LASTEXITCODE -ne 0) { throw "Failed to configure UVdesk." }

# Install bundle public assets. Normally handled by composer.json's own auto-scripts
# (assets:install %PUBLIC_DIR%), skipped above via --no-scripts alongside cache:clear.
Write-Host "[WADDLE] Installing public assets."
docker compose exec -T php php "{{project_path 'website/src'}}/bin/console" assets:install `
    "{{project_path 'website/src'}}/public"
if ($LASTEXITCODE -ne 0) { throw "Failed to install public assets." }

# Mail and site URL (mailbox + support sender). Copied after uvdesk:configure-helpdesk so the wizard
# can't overwrite them; see the rendered files for details.
Write-Host "[WADDLE] Applying mail configuration."
docker compose exec -T php cp "{{project_path 'website/conf/uvdesk/uvdesk_mailbox.yaml'}}" "{{project_path 'website/src'}}/config/packages/uvdesk_mailbox.yaml"
if ($LASTEXITCODE -ne 0) { throw "Failed to apply mailbox configuration." }
docker compose exec -T php cp "{{project_path 'website/conf/uvdesk/waddle.yaml'}}" "{{project_path 'website/src'}}/config/packages/waddle.yaml"
if ($LASTEXITCODE -ne 0) { throw "Failed to apply helpdesk configuration." }

# Clear caches.
Write-Host "[WADDLE] Clearing caches."
docker compose exec -T php php "{{project_path 'website/src'}}/bin/console" cache:clear
if ($LASTEXITCODE -ne 0) { throw "Failed to clear caches." }

# Ensure that daemon-owned directories are owned by the unprivileged worker user.
# Skipped when the php container doesn't run as root (the default on Windows), since its workers
# then already run as the installing user. Avoid double quotes inside the sh -c script since
# PowerShell mangles them when passing arguments to docker.
Write-Host "[WADDLE] Fixing permissions."
docker compose exec -T php sh -c 'if [ $(id -u) = 0 ] && [ $# -gt 0 ]; then chown -R {{get_daemon_user public.php.docker}}:{{get_daemon_group public.php.docker}} $@; fi' sh `
    {{#each (get_daemon_owned_dirs public.website.platform)}}"{{project_path 'website/src'}}/{{this}}" {{/each}}
if ($LASTEXITCODE -ne 0) { throw "Failed to fix permissions." }
